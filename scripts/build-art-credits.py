# Builds js/learn/art.js from art/credits.json (Wikimedia Commons downloads) and
# art/credits-pc.json (Pepper&Carrot by David Revoy, CC BY 4.0).
import json, re, os
root = os.path.join(os.path.dirname(__file__), '..')
out = {}
for f in ['art/credits.json', 'art/credits-pc.json']:
    p = os.path.join(root, f)
    if not os.path.exists(p): continue
    for k, v in json.load(open(p)).items():
        y = re.search(r'1[0-9]{3}s?|20[0-9]{2}', v.get('date', '') or '')
        artist = re.sub(r'(Unknown author)+', 'Unknown artist', v['artist']).replace(', Animation: Nevit Dilmen', '').strip() or 'Unknown artist'
        title = re.sub(r'\.(jpe?g|gif|png|tiff?)$', '', v['title'], flags=re.I)
        title = re.sub(r'^(Formerly )?[^-]*? - ', '', title) if 'Commons' or True else title
        title = re.sub(r' (MET|WGA)\s?\w+$', '', title).replace(' - Google Art Project', '')
        out[k] = dict(src='art/learn/' + v['file'], title=title[:110], artist=artist, year=y.group(0) if y else '', license=v['license'], page=v['page'])
OVR = {
 'ideal-city': dict(title='The Ideal City', artist='Unknown Italian artist (once attributed to Piero della Francesca)'),
 'hokusai': dict(title='Under the Wave off Kanagawa (The Great Wave)'),
 'piranesi': dict(title='The Drawbridge, from the Imaginary Prisons (Carceri)'),
 'friedrich': dict(title='Wanderer above the Sea of Fog'),
 'bierstadt': dict(title='Among the Sierra Nevada, California'),
 'muybridge': dict(title='The Horse in Motion'),
 'muybridge-anim': dict(title='The Horse in Motion (photos played as an animation)'),
 'monet-sunset': dict(title='Rouen Cathedral, Façade (Sunset)'),
 'monet-west': dict(title='Rouen Cathedral, West Façade'),
 'monet-portal': dict(title='Rouen Cathedral, the Portal (Sunlight)'),
}
for k in list(out):
    if k.startswith('lebrun-'):
        out[k]['title'] = out[k]['title'].split(' (from')[0] + ', from Heads Representing the Passions of the Soul'
        out[k]['artist'] = 'After Charles Le Brun (published by Robert Sayer)'
    out[k].update(OVR.get(k, {}))
js = '// Generated by scripts/build-art-credits.py: real artwork used in Inkwell Learning, with credits.\nexport const ART = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
open(os.path.join(root, 'js/learn/art.js'), 'w').write(js)
print(len(out))
